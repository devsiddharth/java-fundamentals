package oop.abstraction;

public class Customer {
    String id;
    String name;
    String dateOfBirth;
    String email;

    public Customer(String id, String name, String dateOfBirth, String email) {
        this.id = id;
        this.name = name;
        this.dateOfBirth = dateOfBirth;
        this.email = email;
    }

}

